function boxed(doc, inv, shop, bp, P, qr) {
  const L = 10, R = 200, W = 190, M = 105;
  doc.setLineWidth(0.3); doc.setDrawColor(0);
  const cols = [10, 17, 78, 102, 124, 138, 160, 181, 200];
  const heads = ['#', 'Item', 'HSN/SAC', 'Rate/ Item', 'Qty', 'Taxable Value', 'Tax Amount', 'Amount'];
  let y = 10;

  doc.rect(L, y, W, 8); font(doc, 10, 'bold', NAVY); spaced(doc, 1.6, () => doc.text(P.title, 105, y + 5.5, { align: 'center' }));
  font(doc, 7.5, 'bold', [60, 60, 60]); spaced(doc, 0.6, () => doc.text('ORIGINAL FOR RECIPIENT', R - 2, y + 5.3, { align: 'right' }));
  y = 18;
  doc.rect(L, y, 95, 30); doc.rect(M, y, 47.5, 15); doc.rect(152.5, y, 47.5, 15); doc.rect(M, y + 15, 47.5, 15); doc.rect(152.5, y + 15, 47.5, 15);
  image(doc, shop.logo, 12, y + 2, 24, 26);
  const sx = shop.logo ? 39 : 13;
  font(doc, 11, 'bold'); doc.text(doc.splitTextToSize(shop.name || 'YOUR SHOP NAME', 62)[0], sx, y + 6);
  let ty = y + 10.5;
  shopLines(doc, shop, bp, 62).slice(0, 6).forEach(l => { font(doc, 8, l.b ? 'bold' : 'normal'); doc.text(l.t, sx, ty); ty += 3.9; });
  const cell = (x, cy, label, value) => { font(doc, 7.5, 'bold', [80, 80, 80]); doc.text(label, x + 2, cy + 5); font(doc, 9.5, 'bold'); doc.text(String(value || '-'), x + 2, cy + 11); };
  cell(M, y, 'Invoice #:', inv.number); cell(152.5, y, 'Invoice Date:', inv.date);
  cell(M, y + 15, 'Place of Supply:', inv.placeOfSupply); cell(152.5, y + 15, 'Due Date:', P.isQuote ? '-' : inv.dueDate || inv.date);
  y = 48;
  doc.rect(L, y, 95, 28); doc.rect(M, y, 95, 28);
  font(doc, 8, 'bold'); doc.text('Customer Details:', 12, y + 5); doc.setFontSize(9); doc.text(inv.customer || '', 12, y + 9.5);
  font(doc, 8, 'normal'); let cy = y + 14;
  [...wrap(doc, custAddress(inv), 88), ...(inv.phone ? [`Ph: ${inv.phone}`] : []), ...(inv.gstin ? [`GSTIN: ${inv.gstin}`] : [])].slice(0, 4).forEach(t => { doc.text(t, 12, cy); cy += 3.9; });
  font(doc, 8, 'bold'); doc.text('Shipping address:', M + 2, y + 5); font(doc, 8, 'normal');
  wrap(doc, inv.shippingAddress || custAddress(inv), 88).slice(0, 5).forEach((t, i) => doc.text(t, M + 2, y + 10 + i * 3.9));
  y = 76;

  const drawHead = () => {
    doc.rect(L, y, W, 7); font(doc, 7.5, 'bold');
    for (let i = 1; i < cols.length - 1; i++) doc.line(cols[i], y, cols[i], y + 7);
    heads.forEach((h, i) => { const x0 = cols[i], x1 = cols[i + 1]; if (i >= 3) doc.text(h, x1 - 1.5, y + 4.7, { align: 'right' }); else doc.text(h, x0 + 1.5, y + 4.7); });
    y += 7;
  };
  drawHead();
  let bodyTop = y;
  const closeBody = bottom => { for (let i = 1; i < cols.length - 1; i++) doc.line(cols[i], bodyTop, cols[i], bottom); doc.line(L, bodyTop, L, bottom); doc.line(R, bodyTop, R, bottom); };
  P.lines.forEach((l, i) => {
    const nm = wrap(doc, l.name, 58); const h = Math.max(nm.length * 4 + 4, 12);
    if (y + h > 262) { closeBody(y); doc.line(L, y, R, y); doc.addPage(); doc.setLineWidth(0.3); y = 10; drawHead(); bodyTop = y; }
    font(doc, 8.5, 'normal'); doc.text(String(i + 1), cols[0] + 1.5, y + 5);
    font(doc, 8.5, 'bold'); doc.text(nm, cols[1] + 1.5, y + 5);
    font(doc, 8.5, 'normal');
    doc.text(String(l.hsn || ''), cols[3] - 1.5, y + 5, { align: 'right' });
    doc.text(inr(l.price), cols[4] - 1.5, y + 5, { align: 'right' }); doc.text(String(l.qty), cols[5] - 1.5, y + 5, { align: 'right' });
    doc.text(inr(l.base), cols[6] - 1.5, y + 5, { align: 'right' }); doc.text(inr(l.t), cols[7] - 1.5, y + 5, { align: 'right' });
    if (l.g) { font(doc, 7.5, 'normal'); doc.text(`(${l.g}%)`, cols[7] - 1.5, y + 8.5, { align: 'right' }); }
    font(doc, 8.5, 'normal'); doc.text(inr(l.amount), cols[8] - 1.5, y + 5, { align: 'right' });
    y += h;
  });
  const minBottom = bodyTop + (doc.getNumberOfPages() === 1 ? 52 : 10);
  if (y < minBottom) y = minBottom;
  closeBody(y); doc.line(L, y, R, y);

  if (y + 120 > 285) { doc.addPage(); doc.setLineWidth(0.3); y = 10; doc.line(L, y, R, y); }
  // totals
  const trow = (label, value, o = {}) => { const h = o.h || 6.5; doc.rect(L, y, W, h); font(doc, o.size || 8.5, o.bold ? 'bold' : 'normal'); doc.text(label, o.right ? o.right : 152, y + h * 0.68, { align: 'right' }); doc.text(value, R - 2, y + h * 0.68, { align: 'right' }); y += h; };
  doc.rect(L, y, 95, 6.5); font(doc, 8); doc.text(`Total Items / Qty : ${P.lines.length} / ${P.qty.toFixed(3)}`, 12, y + 4.4);
  trow('Taxable Amount', rs(P.taxable), { bold: true });
  if (num(inv.discount)) trow('Discount', '- ' + rs(inv.discount));
  if (P.gstOn) { if (P.igst) trow(`IGST`, rs(P.tax)); else { trow('CGST', rs(P.tax / 2)); trow('SGST', rs(P.tax / 2)); } }
  if (num(inv.otherCharges)) trow('Other Charges', rs(inv.otherCharges));
  trow('Total', rs(P.total), { bold: true, size: 13, h: 10 });
  doc.rect(L, y, W, 7); font(doc, 8); doc.text(`Total amount (in words): ${amountInWords(P.total)}.`, 12, y + 4.7); y += 7;

  if (P.gstOn) {
    const groups = {};
    P.lines.forEach(l => { const k = `${l.hsn || '-'}|${l.g}`; (groups[k] ||= { hsn: l.hsn || '-', g: l.g, base: 0, t: 0 }); groups[k].base += l.base; groups[k].t += l.t; });
    const gc = [10, 62, 112, 140, 170, 200], gh = ['HSN/SAC', 'Taxable Value', 'Rate', P.igst ? 'IGST Amount' : 'CGST + SGST', 'Total Tax Amount'];
    doc.rect(L, y, W, 7); font(doc, 8, 'bold'); gh.forEach((h, i) => doc.text(h, i === 0 ? 12 : gc[i + 1] - 2, y + 4.8, { align: i === 0 ? 'left' : 'right' })); y += 7;
    font(doc, 8, 'normal');
    Object.values(groups).forEach(g => { doc.rect(L, y, W, 6); [g.hsn, inr(g.base), `${g.g}%`, inr(g.t), inr(g.t)].forEach((v, i) => doc.text(String(v), i === 0 ? 12 : gc[i + 1] - 2, y + 4.2, { align: i === 0 ? 'left' : 'right' })); y += 6; });
    doc.rect(L, y, W, 6); font(doc, 8, 'bold'); doc.text('TOTAL', 60, y + 4.2, { align: 'right' }); [inr(P.taxable), '', inr(P.tax), inr(P.tax)].forEach((v, i) => v && doc.text(v, gc[i + 2] - 2, y + 4.2, { align: 'right' })); y += 6;
  }
  if (!P.isQuote) { doc.rect(L, y, W, 7); if (P.balance <= 0 && P.total > 0) { font(doc, 9, 'bold', GREEN); doc.text('Amount Paid', R - 2, y + 4.8, { align: 'right' }); } else { font(doc, 9, 'bold'); doc.text(`Balance Due: ${rs(P.balance)}`, R - 2, y + 4.8, { align: 'right' }); } y += 7; }

  // bank / qr / signature
  const bh = 42; doc.rect(L, y, 95, bh); doc.rect(M, y, 95, bh);
  font(doc, 8.5, 'bold'); doc.text('Bank Details:', 12, y + 5);
  font(doc, 8.5, 'normal'); wrap(doc, bankText(inv, bp) || (inv.paymentMode ? `Payment mode: ${inv.paymentMode}` : ''), 52).slice(0, 8).forEach((t, i) => doc.text(t, 12, y + 10 + i * 4.2));
  if (qr) { font(doc, 8, 'bold'); doc.text('Pay using UPI:', 68, y + 5); doc.addImage(qr, 'PNG', 68, y + 8, 28, 28); }
  font(doc, 8, 'normal', [90, 90, 90]); doc.text(`For ${shop.name || ''}`, R - 2, y + 5, { align: 'right' });
  font(doc, 15, 'bolditalic', NAVY); doc.text(doc.splitTextToSize(inv.signature || bp.signatureText || '', 85)[0] || '', M + 47.5, y + 24, { align: 'center' });
  font(doc, 8, 'normal', [90, 90, 90]); doc.text('Authorized Signatory', R - 2, y + bh - 3, { align: 'right' });
  y += bh;
  const nt = wrap(doc, inv.notes, 88), tc = wrap(doc, inv.terms, 88), nh = Math.max(20, Math.max(nt.length, tc.length) * 3.9 + 9);
  if (y + nh > 285) { doc.addPage(); doc.setLineWidth(0.3); y = 10; }
  doc.rect(L, y, 95, nh); doc.rect(M, y, 95, nh);
  font(doc, 8.5, 'bold'); doc.text('Notes:', 12, y + 5); doc.text('Terms and Conditions:', M + 2, y + 5);
  font(doc, 8, 'normal'); nt.forEach((t, i) => doc.text(t, 12, y + 10 + i * 3.9)); tc.forEach((t, i) => doc.text(t, M + 2, y + 10 + i * 3.9));
}

/* ───────────────────────── CLEAN ───────────────────────── */
function clean(doc, inv, shop, bp, P, qr) {
  let y = 14;
  const ensure = h => { if (y + h > 280) { doc.addPage(); y = 16; } };
  font(doc, 11, 'bold', NAVY); spaced(doc, 1.8, () => doc.text(P.title, 14, y));
  font(doc, 7.5, 'bold', [70, 70, 70]); spaced(doc, 0.7, () => doc.text('ORIGINAL FOR RECIPIENT', 196, y - 1, { align: 'right' }));
  image(doc, shop.logo, 146, y + 2, 50, 22, 'right');
  y += 10; font(doc, 16, 'bold'); doc.text(doc.splitTextToSize(shop.name || 'YOUR SHOP NAME', 125)[0], 14, y); y += 6;
  shopLines(doc, shop, bp, 125).forEach(l => { font(doc, 9, l.b ? 'bold' : 'normal'); doc.text(l.t, 14, y); y += 4.4; });
  y = Math.max(y, 48) + 6;
  const meta = (x, label, value) => { font(doc, 8.5, 'bold', [70, 70, 70]); doc.text(label, x, y); const w = doc.getTextWidth(label); font(doc, 9.5, 'bold'); doc.text(String(value || '-'), x + w + 1.5, y); };
  meta(14, 'Invoice #:', inv.number); meta(78, 'Invoice Date:', inv.date); if (!P.isQuote) meta(142, 'Due Date:', inv.dueDate || inv.date);
  y += 8;
  const cb = (x, head, lines) => { font(doc, 8.5, 'bold', [70, 70, 70]); doc.text(head, x, y); let cy = y + 4.8; lines.forEach((t, i) => { font(doc, 9, i === 0 && head === 'Customer Details:' ? 'bold' : 'normal'); doc.text(t, x, cy); cy += 4.4; }); return cy; };
  const e1 = cb(14, 'Customer Details:', [inv.customer || '', ...(inv.phone ? [`Ph: ${inv.phone}`] : []), ...(inv.gstin ? [`GSTIN: ${inv.gstin}`] : [])]);
  const e2 = cb(78, 'Billing address:', wrap(doc, custAddress(inv), 58).slice(0, 4));
  const e3 = cb(142, 'Shipping address:', wrap(doc, inv.shippingAddress || custAddress(inv), 54).slice(0, 4));
  y = Math.max(e1, e2, e3);
  if (inv.placeOfSupply) { font(doc, 8.5, 'bold', [70, 70, 70]); doc.text('Place of Supply:', 14, y + 1); font(doc, 9.5, 'bold'); doc.text(String(inv.placeOfSupply), 14 + doc.getTextWidth('Place of Supply:') + 1.5, y + 1); y += 5; }
  y += 5;

  const X = { n: 14, item: 24, rate: 112, qty: 128, base: 152, tax: 176, amt: 196 };
  const head = () => { doc.setDrawColor(...NAVY); doc.setLineWidth(0.5); doc.line(14, y - 4.5, 196, y - 4.5); font(doc, 8.5, 'bold');
    doc.text('#', X.n, y); doc.text('Item', X.item, y); doc.text('Rate/ Item', X.rate, y, { align: 'right' }); doc.text('Qty', X.qty, y, { align: 'right' }); doc.text('Taxable Value', X.base, y, { align: 'right' }); doc.text('Tax Amount', X.tax, y, { align: 'right' }); doc.text('Amount', X.amt, y, { align: 'right' });
    doc.line(14, y + 2.5, 196, y + 2.5); y += 8; };
  head();
  P.lines.forEach((l, i) => {
    const nm = wrap(doc, l.name, 80), h = nm.length * 4.6 + (l.hsn ? 4.6 : 0) + 4;
    ensure(h); if (y === 16) head();
    font(doc, 9, 'normal'); doc.text(String(i + 1), X.n, y);
    font(doc, 9.5, 'bold'); doc.text(nm, X.item, y);
    font(doc, 8.5, 'normal'); if (l.hsn) doc.text(`HSN: ${l.hsn}`, X.item, y + nm.length * 4.6);
    font(doc, 9, 'normal'); doc.text(inr(l.price), X.rate, y, { align: 'right' }); doc.text(String(l.qty), X.qty, y, { align: 'right' }); doc.text(inr(l.base), X.base, y, { align: 'right' });
    doc.text(P.gstOn ? `${inr(l.t)} (${l.g}%)` : inr(l.t), X.tax + 4, y, { align: 'right' }); doc.text(inr(l.amount), X.amt, y, { align: 'right' });
    y += h; doc.setDrawColor(...GREY); doc.setLineWidth(0.2); doc.line(14, y - 3, 196, y - 3);
  });
  doc.setDrawColor(...NAVY); doc.setLineWidth(0.5); doc.line(14, y - 3, 196, y - 3); y += 3;

  ensure(60);
  const tr = (label, value, o = {}) => { font(doc, o.size || 9, 'bold'); doc.text(label, 150, y, { align: 'right' }); doc.text(value, 196, y, { align: 'right' }); y += o.step || 5.4; };
  font(doc, 8, 'normal', [90, 90, 90]); doc.text(`Total Items / Qty : ${P.lines.length} / ${P.qty.toFixed(3)}`, 14, y);
  tr('Taxable Amount', rs(P.taxable));
  if (num(inv.discount)) tr('Discount', '- ' + rs(inv.discount));
  if (P.gstOn) { if (P.igst) tr('IGST', rs(P.tax)); else { tr('CGST', rs(P.tax / 2)); tr('SGST', rs(P.tax / 2)); } }
  if (num(inv.otherCharges)) tr('Other Charges', rs(inv.otherCharges));
  doc.setDrawColor(...NAVY); doc.line(110, y - 2.5, 196, y - 2.5); y += 3; tr('Total', rs(P.total), { size: 14, step: 8 });
  font(doc, 8.5, 'normal'); wrap(doc, `Total amount (in words): ${amountInWords(P.total)}.`, 182).forEach(t => { doc.text(t, 14, y); y += 4.2; });
  doc.line(14, y, 196, y); y += 5;
  if (!P.isQuote) { if (P.balance <= 0 && P.total > 0) { font(doc, 10, 'bold', GREEN); doc.text('Amount Paid', 196, y, { align: 'right' }); } else { tr('Amount Payable:', rs(P.balance), { size: 10 }); y -= 5.4; } y += 9; }

  ensure(50); const top = y;
  if (qr) { font(doc, 9, 'bold'); doc.text('Pay using UPI:', 14, y); doc.addImage(qr, 'PNG', 14, y + 3, 30, 30); }
  const bx = qr ? 52 : 14; font(doc, 9, 'bold'); doc.text('Bank Details:', bx, y);
  font(doc, 9, 'normal'); wrap(doc, bankText(inv, bp) || (inv.paymentMode ? `Payment mode: ${inv.paymentMode}` : ''), 80).slice(0, 7).forEach((t, i) => doc.text(t, bx, y + 5 + i * 4.4));
  font(doc, 8.5, 'normal', [90, 90, 90]); doc.text(`For ${shop.name || ''}`, 170, top, { align: 'center' });
  font(doc, 15, 'bolditalic', NAVY); doc.text(doc.splitTextToSize(inv.signature || bp.signatureText || '', 55)[0] || '', 170, top + 18, { align: 'center' });
  font(doc, 8.5, 'normal', [90, 90, 90]); doc.text('Authorized Signatory', 170, top + 30, { align: 'center' });
  y = top + 38;
  if (inv.notes) { ensure(14); font(doc, 9, 'bold'); doc.text('Notes:', 14, y); font(doc, 9, 'normal'); wrap(doc, inv.notes, 182).forEach((t, i) => doc.text(t, 14, y + 5 + i * 4.2)); y += 8 + wrap(doc, inv.notes, 182).length * 4.2; }
  if (inv.terms) { const t = wrap(doc, inv.terms, 182); ensure(10 + t.length * 3.6); font(doc, 9, 'bold'); doc.text('Terms and Conditions:', 14, y); font(doc, 7.5, 'normal'); t.forEach((s, i) => doc.text(s, 14, y + 5 + i * 3.6)); }
}

/* ───────────────────────── COMPACT ───────────────────────── */

// GST invoice layouts: "boxed", "clean" and "compact"
import QRCode from 'qrcode';
import { amountInWords } from './numwords.js';
import { docTitle } from './docTitle.js';

const NAVY = [16, 52, 120], GREY = [200, 205, 212], BLACK = [20, 24, 30], GREEN = [22, 140, 80];
const num = v => Number(v) || 0;
const inr = n => num(n).toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
const rs = n => 'Rs. ' + inr(n);

function prep(inv) {
  const gstOn = !!inv.taxEnabled;
  const lines = (inv.items || []).map(it => {
    const base = num(it.qty) * num(it.price) - num(it.discount);
    const g = gstOn ? num(it.gst ?? inv.taxRate) : 0;
    const t = base * g / 100;
    return { ...it, base, g, t, amount: base + t };
  });
  const total = num(inv.total), paid = num(inv.paidAmount);
  return {
    lines, gstOn, total, paid, balance: Math.max(0, total - paid),
    qty: lines.reduce((s, l) => s + num(l.qty), 0),
    taxable: lines.reduce((s, l) => s + l.base, 0), tax: lines.reduce((s, l) => s + l.t, 0),
    igst: inv.gstMode === 'IGST', isQuote: (inv.kind || 'invoice') !== 'invoice',
    title: docTitle(inv)
  };
}

async function makeQr(inv, shop, P, bp) {
  const upi = (inv.upiId ?? bp.upiId ?? '').trim();
  if (!upi || P.isQuote) return null;
  const url = `upi://pay?pa=${encodeURIComponent(upi)}&pn=${encodeURIComponent(shop.name || '')}&cu=INR&tn=${encodeURIComponent(inv.number || '')}${P.balance > 0 ? `&am=${P.balance.toFixed(2)}` : ''}`;
  try { return await QRCode.toDataURL(url, { margin: 0, width: 260 }); } catch { return null; }
}

function image(doc, data, x, y, w, h, align = 'left') {
  if (!data) return;
  try {
    const fmt = /^data:image\/png/.test(data) ? 'PNG' : /^data:image\/webp/.test(data) ? 'WEBP' : 'JPEG';
    const p = doc.getImageProperties(data);
    const k = Math.min(w / p.width, h / p.height);
    const iw = p.width * k, ih = p.height * k;
    doc.addImage(data, fmt, align === 'right' ? x + w - iw : x, y + (h - ih) / 2, iw, ih);
  } catch { /* skip unreadable image */ }
}

const wrap = (doc, text, w) => (text ? doc.splitTextToSize(String(text), w) : []);
const font = (doc, size, style = 'normal', color = BLACK) => { doc.setFontSize(size); doc.setFont('helvetica', style); doc.setTextColor(...color); };
const spaced = (doc, space, fn) => { doc.setCharSpace?.(space); fn(); doc.setCharSpace?.(0); };

function shopLines(doc, shop, bp, w) {
  return [
    ...(shop.gstin ? [{ t: `GSTIN ${shop.gstin}`, b: true }] : []),
    ...wrap(doc, [shop.address, bp.state && !String(shop.address || '').includes(bp.state) ? bp.state : '', bp.pinCode].filter(Boolean).join(', '), w).map(t => ({ t })),
    ...(shop.phone ? [{ t: `Mobile ${shop.phone}` }] : []),
    ...(shop.email ? [{ t: `Email ${shop.email}` }] : [])
  ];
}
const custAddress = inv => inv.address || '';

function footers(doc, shop) {
  const n = doc.getNumberOfPages();
  for (let i = 1; i <= n; i++) { doc.setPage(i); font(doc, 8, 'normal'); doc.text(`Page ${i} / ${n}`, 10, 291); doc.text('Generated by ShopMaster Pro', 40, 291); }
}

function bankText(inv, bp) { return String(inv.bankDetails ?? bp.bankDetails ?? '').trim(); }

